function ConvertTo-ICTPsLiteral {
    <# A single-quoted PowerShell string literal. #>
    [CmdletBinding()]
    [OutputType([string])]
    param([AllowEmptyString()][string]$Value)
    # Also doubles the typographic quotes that PowerShell treats as string delimiters.
    return "'" + [System.Management.Automation.Language.CodeGeneration]::EscapeSingleQuotedStringContent($Value) + "'"
}

function New-ICTRepairScript {
    <#
        Builds the script that removes the Intune enrollment and starts deviceenroller.exe.
        It runs as SYSTEM from a scheduled task, so it finishes even when the SSH session
        drops, and it can delete keys that only SYSTEM may delete. Each stage appends one
        JSON line to the state file: {Stage, Status, Detail, Time}.
    #>
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [AllowEmptyCollection()][string[]]$RegistryPath = @(),
        [AllowEmptyCollection()][string[]]$EnrollmentId = @(),
        [AllowEmptyCollection()][string[]]$Thumbprint = @(),
        [Parameter(Mandatory)][string]$EnrollerArgument,
        [Parameter(Mandatory)][string]$StatePath
    )

    $list = { param([string[]]$Items) '@(' + ((@($Items) | Where-Object { $_ } | ForEach-Object { ConvertTo-ICTPsLiteral $_ }) -join ', ') + ')' }

    return @"
# Generated by IntuneComplianceTool. Removes an Intune MDM enrollment and enrolls again (runs as SYSTEM).
`$ErrorActionPreference = 'Stop'
`$statePath = $(ConvertTo-ICTPsLiteral $StatePath)
`$enrollmentIds = $(& $list $EnrollmentId)
`$registryPaths = $(& $list $RegistryPath)
`$thumbprints = $(& $list $Thumbprint)

function Write-State([string]`$Stage, [string]`$Status, [string]`$Detail) {
    `$line = [pscustomobject]@{ Stage = `$Stage; Status = `$Status; Detail = `$Detail; Time = [datetime]::UtcNow.ToString('o') } | ConvertTo-Json -Compress
    Add-Content -LiteralPath `$statePath -Value `$line -Encoding UTF8
}

`$stage = 'start'
try {
    Write-State 'start' 'Running' ''

    `$stage = 'tasks'
    `$scheduler = New-Object -ComObject 'Schedule.Service'
    `$scheduler.Connect()
    `$removedTasks = 0
    foreach (`$id in `$enrollmentIds) {
        try { `$folder = `$scheduler.GetFolder('\Microsoft\Windows\EnterpriseMgmt\' + `$id) } catch { continue }
        foreach (`$task in @(`$folder.GetTasks(1))) { `$folder.DeleteTask(`$task.Name, 0); `$removedTasks++ }
        `$scheduler.GetFolder('\Microsoft\Windows\EnterpriseMgmt').DeleteFolder(`$id, 0)
    }
    Write-State 'tasks' 'Done' ('{0} tasks removed' -f `$removedTasks)

    `$stage = 'registry'
    `$removedKeys = 0
    foreach (`$path in `$registryPaths) {
        if (Test-Path -LiteralPath `$path) { Remove-Item -LiteralPath `$path -Recurse -Force; `$removedKeys++ }
    }
    `$logger = 'HKLM:\SOFTWARE\Microsoft\Provisioning\OMADM\Logger'
    `$current = (Get-ItemProperty -LiteralPath `$logger -ErrorAction SilentlyContinue).CurrentEnrollmentId
    if (`$current -and (`$enrollmentIds -contains `$current)) { Remove-ItemProperty -LiteralPath `$logger -Name 'CurrentEnrollmentId' }
    Write-State 'registry' 'Done' ('{0} registry keys removed' -f `$removedKeys)

    `$stage = 'certificates'
    `$removedCertificates = 0
    foreach (`$thumbprint in `$thumbprints) {
        `$certificatePath = 'Cert:\LocalMachine\My\' + `$thumbprint
        if (Test-Path -LiteralPath `$certificatePath) { Remove-Item -LiteralPath `$certificatePath -Force; `$removedCertificates++ }
    }
    Write-State 'certificates' 'Done' ('{0} certificates removed' -f `$removedCertificates)

    `$stage = 'enroll'
    `$enroller = Join-Path `$env:windir 'System32\deviceenroller.exe'
    `$process = Start-Process -FilePath `$enroller -ArgumentList $(ConvertTo-ICTPsLiteral $EnrollerArgument) -PassThru -WindowStyle Hidden
    if (`$process.WaitForExit(180000)) { Write-State 'enroll' 'Done' ('exit {0}' -f `$process.ExitCode) }
    else { Write-State 'enroll' 'Done' 'still running after 180 s' }

    Write-State 'end' 'Succeeded' ''
}
catch {
    Write-State 'end' 'Failed' ('{0}: {1}' -f `$stage, `$_.Exception.Message)
}
"@
}

function New-ICTRestoreText {
    <# restore.ps1: puts a removed enrollment back from the backup folder. It must run as SYSTEM. #>
    [CmdletBinding()]
    [OutputType([string[]])]
    param(
        [Parameter(Mandatory)][string]$BackupPath,
        [AllowEmptyCollection()][string[]]$RegistryFile = @(),
        [AllowEmptyCollection()][object[]]$Task = @(),
        [AllowEmptyCollection()][object[]]$Certificate = @(),
        [AllowNull()][string]$CurrentEnrollmentId
    )
    $base = $BackupPath.TrimEnd('\') + '\'   # Windows paths, built as text so this also works off Windows
    $lines = @(
        '# Puts back the Intune enrollment removed by IntuneComplianceTool. Use it only if the repair'
        '# failed and no new enrollment was created. Some keys can only be written as SYSTEM, so run:'
        ('#   schtasks /create /tn ICT-Restore /ru SYSTEM /sc once /st 00:00 /f /tr "powershell -NoProfile -ExecutionPolicy Bypass -File \"{0}restore.ps1\""' -f $base)
        '#   schtasks /run /tn ICT-Restore'
        '#   schtasks /delete /tn ICT-Restore /f'
        "`$ErrorActionPreference = 'Continue'"
    )
    foreach ($file in $RegistryFile) { $lines += '& reg.exe import {0}' -f (ConvertTo-ICTPsLiteral ($base + $file)) }
    foreach ($item in $Task) {
        $lines += 'Register-ScheduledTask -Xml (Get-Content -Raw -LiteralPath {0}) -TaskName {1} -TaskPath {2} -Force' -f (ConvertTo-ICTPsLiteral ($base + $item.File)), (ConvertTo-ICTPsLiteral $item.TaskName), (ConvertTo-ICTPsLiteral $item.TaskPath)
    }
    if ($CurrentEnrollmentId) {
        $lines += "New-ItemProperty -Path 'HKLM:\SOFTWARE\Microsoft\Provisioning\OMADM\Logger' -Name 'CurrentEnrollmentId' -Value {0} -PropertyType String -Force" -f (ConvertTo-ICTPsLiteral $CurrentEnrollmentId)
    }
    foreach ($item in $Certificate) {
        # The private key is not deleted together with the certificate, so repairstore can reattach it.
        $lines += '& certutil.exe -addstore my {0}' -f (ConvertTo-ICTPsLiteral ($base + $item.File))
        $lines += '& certutil.exe -repairstore my {0}' -f $item.Thumbprint
    }
    return [string[]]$lines
}

function Test-ICTEnrollmentUser {
    <#
        Whether the signed-in console user can provide the Entra token that
        UserCredential enrollment needs. Returns $null when fine, otherwise the reason.
    #>
    [CmdletBinding()]
    [OutputType([string])]
    param([AllowNull()][AllowEmptyString()][string]$User, [string[]]$ComputerName = @(), [AllowEmptyCollection()][string[]]$ExcludeAccount = @())

    if ([string]::IsNullOrWhiteSpace($User)) { return 'nobody is signed in at the console' }
    $parts = $User.Split('\')
    $domain = $(if ($parts.Count -gt 1) { $parts[0] } else { '' })
    $name = $parts[-1]
    foreach ($account in $ExcludeAccount) {
        if ($account -and $name -eq $account.Split('\')[-1]) { return "$User is the SSH / LAPS admin account" }
    }
    if ($domain -and @($ComputerName | Where-Object { $_ -and $_ -eq $domain }).Count -gt 0) { return "$User is a local account" }
    return $null
}
