function ConvertTo-ICTPsLiteral {
    <# A single-quoted PowerShell string literal. #>
    [CmdletBinding()]
    [OutputType([string])]
    param([AllowEmptyString()][string]$Value)
    # Also doubles the typographic quotes that PowerShell treats as string delimiters.
    return "'" + [System.Management.Automation.Language.CodeGeneration]::EscapeSingleQuotedStringContent($Value) + "'"
}

function New-ICTRepairScript {
    <#
        Builds the script that removes the Intune enrollment and starts deviceenroller.exe.
        It runs as SYSTEM from a scheduled task, so it finishes even when the SSH session
        drops, and it can delete keys that only SYSTEM may delete. Each stage appends one
        JSON line to the state file: {Stage, Status, Detail, Time}.
    #>
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [AllowEmptyCollection()][string[]]$RegistryPath = @(),
        [AllowEmptyCollection()][string[]]$EnrollmentId = @(),
        [AllowEmptyCollection()][string[]]$Thumbprint = @(),
        [Parameter(Mandatory)][string]$EnrollerArgument,
        [Parameter(Mandatory)][string]$StatePath,
        [string]$EnrollerPath   # only the integration tests pass this, to run a harmless program instead
    )

    $list = { param([string[]]$Items) '@(' + ((@($Items) | Where-Object { $_ } | ForEach-Object { ConvertTo-ICTPsLiteral $_ }) -join ', ') + ')' }

    return @"
# Generated by IntuneComplianceTool. Removes an Intune MDM enrollment and enrolls again (runs as SYSTEM).
`$ErrorActionPreference = 'Stop'
`$statePath = $(ConvertTo-ICTPsLiteral $StatePath)
`$enrollmentIds = $(& $list $EnrollmentId)
`$registryPaths = $(& $list $RegistryPath)
`$thumbprints = $(& $list $Thumbprint)

function Write-State([string]`$Stage, [string]`$Status, [string]`$Detail) {
    `$line = [pscustomobject]@{ Stage = `$Stage; Status = `$Status; Detail = `$Detail; Time = [datetime]::UtcNow.ToString('o') } | ConvertTo-Json -Compress
    Add-Content -LiteralPath `$statePath -Value `$line -Encoding UTF8
}

`$stage = 'start'
try {
    Write-State 'start' 'Running' ''

    `$stage = 'tasks'
    `$scheduler = New-Object -ComObject 'Schedule.Service'
    `$scheduler.Connect()
    `$removedTasks = 0
    foreach (`$id in `$enrollmentIds) {
        try { `$folder = `$scheduler.GetFolder('\Microsoft\Windows\EnterpriseMgmt\' + `$id) } catch { continue }
        foreach (`$task in @(`$folder.GetTasks(1))) { `$folder.DeleteTask(`$task.Name, 0); `$removedTasks++ }
        `$scheduler.GetFolder('\Microsoft\Windows\EnterpriseMgmt').DeleteFolder(`$id, 0)
    }
    Write-State 'tasks' 'Done' ('{0} tasks removed' -f `$removedTasks)

    `$stage = 'registry'
    `$removedKeys = 0
    foreach (`$path in `$registryPaths) {
        if (Test-Path -LiteralPath `$path) { Remove-Item -LiteralPath `$path -Recurse -Force; `$removedKeys++ }
    }
    `$logger = 'HKLM:\SOFTWARE\Microsoft\Provisioning\OMADM\Logger'
    `$current = (Get-ItemProperty -LiteralPath `$logger -ErrorAction SilentlyContinue).CurrentEnrollmentId
    if (`$current -and (`$enrollmentIds -contains `$current)) { Remove-ItemProperty -LiteralPath `$logger -Name 'CurrentEnrollmentId' }
    Write-State 'registry' 'Done' ('{0} registry keys removed' -f `$removedKeys)

    `$stage = 'certificates'
    `$removedCertificates = 0
    foreach (`$thumbprint in `$thumbprints) {
        `$certificatePath = 'Cert:\LocalMachine\My\' + `$thumbprint
        if (Test-Path -LiteralPath `$certificatePath) { Remove-Item -LiteralPath `$certificatePath -Force; `$removedCertificates++ }
    }
    Write-State 'certificates' 'Done' ('{0} certificates removed' -f `$removedCertificates)

    `$stage = 'enroll'
    `$enroller = $(if ($EnrollerPath) { ConvertTo-ICTPsLiteral $EnrollerPath } else { "Join-Path `$env:windir 'System32\deviceenroller.exe'" })
    `$process = Start-Process -FilePath `$enroller -ArgumentList $(ConvertTo-ICTPsLiteral $EnrollerArgument) -PassThru -WindowStyle Hidden
    if (`$process.WaitForExit(180000)) { Write-State 'enroll' 'Done' ('exit {0}' -f `$process.ExitCode) }
    else { Write-State 'enroll' 'Done' 'still running after 180 s' }

    Write-State 'end' 'Succeeded' ''
}
catch {
    Write-State 'end' 'Failed' ('{0}: {1}' -f `$stage, `$_.Exception.Message)
}
"@
}

function New-ICTRestoreText {
    <# restore.ps1: puts a removed enrollment back from the backup folder. It must run as SYSTEM. #>
    [CmdletBinding()]
    [OutputType([string[]])]
    param(
        [Parameter(Mandatory)][string]$BackupPath,
        [AllowEmptyCollection()][string[]]$RegistryFile = @(),
        [AllowEmptyCollection()][object[]]$Task = @(),
        [AllowEmptyCollection()][object[]]$Certificate = @(),
        [AllowNull()][string]$CurrentEnrollmentId
    )
    $base = $BackupPath.TrimEnd('\') + '\'   # Windows paths, built as text so this also works off Windows
    $lines = @(
        '# Puts back the Intune enrollment removed by IntuneComplianceTool. Use it only if the repair'
        '# failed and no new enrollment was created. Some keys can only be written as SYSTEM, so run:'
        ('#   schtasks /create /tn ICT-Restore /ru SYSTEM /sc once /st 00:00 /f /tr "powershell -NoProfile -ExecutionPolicy Bypass -File \"{0}restore.ps1\""' -f $base)
        '#   schtasks /run /tn ICT-Restore'
        '#   schtasks /delete /tn ICT-Restore /f'
        "`$ErrorActionPreference = 'Continue'"
    )
    foreach ($file in $RegistryFile) { $lines += '& reg.exe import {0}' -f (ConvertTo-ICTPsLiteral ($base + $file)) }
    foreach ($item in $Task) {
        $lines += 'Register-ScheduledTask -Xml (Get-Content -Raw -LiteralPath {0}) -TaskName {1} -TaskPath {2} -Force' -f (ConvertTo-ICTPsLiteral ($base + $item.File)), (ConvertTo-ICTPsLiteral $item.TaskName), (ConvertTo-ICTPsLiteral $item.TaskPath)
    }
    if ($CurrentEnrollmentId) {
        $lines += "New-ItemProperty -Path 'HKLM:\SOFTWARE\Microsoft\Provisioning\OMADM\Logger' -Name 'CurrentEnrollmentId' -Value {0} -PropertyType String -Force" -f (ConvertTo-ICTPsLiteral $CurrentEnrollmentId)
    }
    foreach ($item in $Certificate) {
        # The private key is not deleted together with the certificate, so repairstore can reattach it.
        $lines += '& certutil.exe -addstore my {0}' -f (ConvertTo-ICTPsLiteral ($base + $item.File))
        $lines += '& certutil.exe -repairstore my {0}' -f $item.Thumbprint
    }
    return [string[]]$lines
}

function Test-ICTEnrollmentUser {
    <#
        Whether the signed-in console user can provide the Entra token that
        UserCredential enrollment needs. Returns $null when fine, otherwise the reason.
    #>
    [CmdletBinding()]
    [OutputType([string])]
    param([AllowNull()][AllowEmptyString()][string]$User, [string[]]$ComputerName = @(), [AllowEmptyCollection()][string[]]$ExcludeAccount = @())

    if ([string]::IsNullOrWhiteSpace($User)) { return 'nobody is signed in at the console' }
    $parts = $User.Split('\')
    $domain = $(if ($parts.Count -gt 1) { $parts[0] } else { '' })
    $name = $parts[-1]
    foreach ($account in $ExcludeAccount) {
        if ($account -and $name -eq $account.Split('\')[-1]) { return "$User is the SSH / LAPS admin account" }
    }
    if ($domain -and @($ComputerName | Where-Object { $_ -and $_ -eq $domain }).Count -gt 0) { return "$User is a local account" }
    return $null
}

function New-ICTUpdateRepairScript {
    <#
        Builds the script that resets the Windows Update components (runs as SYSTEM):
        re-enables disabled update services, stops them (with a time limit), sets
        SoftwareDistribution and catroot2 aside (renamed; the first and the newest copy
        are kept), starts the services and their stopped dependents again, optionally runs
        DISM /RestoreHealth and sfc /scannow, and starts a new scan.
        -NoRepairSource: DISM is skipped, because the device may not use Windows Update
        as its repair source (WSUS or blocking policy without RepairContentServerSource).
        Written as a template so nothing in it needs escaping.
    #>
    [CmdletBinding()]
    [OutputType([string])]
    param([Parameter(Mandatory)][string]$StatePath, [Parameter(Mandatory)][string]$Stamp, [switch]$Deep, [switch]$NoRepairSource)

    $template = @'
# Generated by IntuneComplianceTool. Resets the Windows Update components (runs as SYSTEM).
$ErrorActionPreference = 'Stop'
$statePath = __STATE__
$stamp = __STAMP__
$deep = __DEEP__
$repairSource = __SOURCE__

function Write-State([string]$Stage, [string]$Status, [string]$Detail) {
    $line = [pscustomobject]@{ Stage = $Stage; Status = $Status; Detail = $Detail; Time = [datetime]::UtcNow.ToString('o') } | ConvertTo-Json -Compress
    Add-Content -LiteralPath $statePath -Value $line -Encoding UTF8
}

function Stop-UpdateService([string]$Name, [bool]$Required) {
    # Stop-Service has no time limit; a service stuck in StopPending must not hang the repair.
    $service = Get-Service -Name $Name -ErrorAction SilentlyContinue
    if ($null -eq $service) { return }
    for ($i = 0; $i -lt 3 -and "$($service.Status)" -ne 'Stopped'; $i++) {
        try { $service.Stop() } catch { Start-Sleep -Seconds 1 }
        try { $service.WaitForStatus('Stopped', [timespan]::FromSeconds(30)) } catch { Start-Sleep -Seconds 1 }
        $service.Refresh()
    }
    if ($Required -and "$($service.Status)" -ne 'Stopped') { throw "$Name does not stop." }
}

function Set-Aside([string]$Path, [bool]$Required) {
    for ($i = 0; $i -lt 3; $i++) {
        if (-not (Test-Path -LiteralPath $Path)) { return 'not present' }
        try { Rename-Item -LiteralPath $Path -NewName ((Split-Path -Path $Path -Leaf) + '.ict-' + $stamp); return 'set aside' }
        catch {
            # Trigger-start services can come back in between: stop them again and retry.
            Stop-UpdateService 'wuauserv' $false; Stop-UpdateService 'BITS' $false; Stop-UpdateService 'DoSvc' $false
            Start-Sleep -Seconds 2
        }
    }
    if ($Required) { throw "$Path is in use and could not be set aside." }
    return 'kept (in use)'
}

function Remove-OldCopy([string]$Folder, [string]$Name) {
    # Keep the first copy (the original data) and the one made now; remove the ones in between.
    $copies = @(Get-ChildItem -LiteralPath $Folder -Directory -Filter ($Name + '.ict-*') -ErrorAction SilentlyContinue | Sort-Object CreationTimeUtc)
    foreach ($copy in $copies) {
        if ($copy -eq $copies[0] -or $copy.Name -eq ($Name + '.ict-' + $stamp)) { continue }
        Remove-Item -LiteralPath $copy.FullName -Recurse -Force -ErrorAction SilentlyContinue
    }
}

function Format-Code([int64]$Code) { '0x{0:X8}' -f ($Code -band 4294967295) }

$order = @('CryptSvc', 'BITS', 'wuauserv', 'UsoSvc', 'DoSvc')
$dependents = @()
$stage = 'start'
$stopped = $false
try {
    Write-State 'start' 'Running' ''

    $stage = 'services'
    $enabled = @()
    foreach ($item in @(@('wuauserv', 'Manual'), @('BITS', 'Manual'), @('CryptSvc', 'Automatic'))) {
        $service = Get-Service -Name $item[0] -ErrorAction SilentlyContinue
        if ($service -and "$($service.StartType)" -eq 'Disabled') { Set-Service -Name $item[0] -StartupType $item[1]; $enabled += $item[0] }
    }
    $uso = Get-Service -Name 'UsoSvc' -ErrorAction SilentlyContinue
    if ($uso -and "$($uso.StartType)" -eq 'Disabled') { & sc.exe config UsoSvc start= delayed-auto | Out-Null; $enabled += 'UsoSvc' }
    Write-State 'services' 'Done' $(if ($enabled.Count) { 're-enabled ' + ($enabled -join ', ') } else { 'all enabled' })

    $stage = 'stop'
    $dependents = @((Get-Service -Name 'CryptSvc').DependentServices | Where-Object { "$($_.Status)" -eq 'Running' } | ForEach-Object { $_.Name })
    $stopped = $true
    Stop-UpdateService 'UsoSvc' $false
    Stop-UpdateService 'DoSvc' $false
    Stop-UpdateService 'wuauserv' $true
    Stop-UpdateService 'BITS' $true
    foreach ($name in $dependents) { Stop-UpdateService $name $false }
    Stop-UpdateService 'CryptSvc' $false
    Write-State 'stop' 'Done' 'update services stopped'

    $stage = 'reset'
    $distribution = Set-Aside (Join-Path $env:windir 'SoftwareDistribution') $true
    $catroot = Set-Aside (Join-Path $env:windir 'System32\catroot2') $false
    Remove-OldCopy $env:windir 'SoftwareDistribution'
    Remove-OldCopy (Join-Path $env:windir 'System32') 'catroot2'
    Write-State 'reset' 'Done' ('SoftwareDistribution {0}, catroot2 {1}' -f $distribution, $catroot)

    $stage = 'start-services'
    foreach ($name in $order + $dependents) { if (Get-Service -Name $name -ErrorAction SilentlyContinue) { Start-Service -Name $name -ErrorAction SilentlyContinue } }
    $stopped = $false
    Write-State 'start-services' 'Done' 'update services started'

    if ($deep -and -not $repairSource) {
        Write-State 'dism' 'Done' 'skipped: Windows Update is not this device''s repair source'
    }
    elseif ($deep) {
        $stage = 'dism'
        & (Join-Path $env:windir 'System32\dism.exe') /Online /Cleanup-Image /RestoreHealth /NoRestart | Out-Null
        $dism = $LASTEXITCODE
        if ($dism -eq 3010) { Write-State 'dism' 'Done' 'repaired, restart required' }
        else {
            Write-State 'dism' 'Done' $(if ($dism -eq 0) { 'exit 0' } else { 'failed ' + (Format-Code $dism) })
            $stage = 'sfc'
            & (Join-Path $env:windir 'System32\sfc.exe') /scannow | Out-Null
            Write-State 'sfc' 'Done' $(if ($LASTEXITCODE -eq 0) { 'exit 0' } else { 'exit ' + (Format-Code $LASTEXITCODE) })
        }
    }

    $stage = 'scan'
    $client = Join-Path $env:windir 'System32\UsoClient.exe'
    $started = $false
    if (Test-Path -LiteralPath $client) { & $client StartScan | Out-Null; $started = ($LASTEXITCODE -eq 0) }
    if (-not $started) { (New-Object -ComObject 'Microsoft.Update.AutoUpdate').DetectNow() }
    Write-State 'scan' 'Done' 'scan started'

    Write-State 'end' 'Succeeded' ''
}
catch {
    Write-State 'end' 'Failed' ('{0}: {1}' -f $stage, $_.Exception.Message)
}
finally {
    if ($stopped) { foreach ($name in $order + $dependents) { Start-Service -Name $name -ErrorAction SilentlyContinue } }
}
'@
    $text = $template.Replace('__STATE__', (ConvertTo-ICTPsLiteral $StatePath)).Replace('__STAMP__', (ConvertTo-ICTPsLiteral $Stamp))
    return $text.Replace('__DEEP__', $(if ($Deep) { '$true' } else { '$false' })).Replace('__SOURCE__', $(if ($NoRepairSource) { '$false' } else { '$true' }))
}

function Wait-ICTSystemScript {
    <#
        Polls the state file of a SYSTEM script until it reports 'end', its task stops
        without doing so, or the timeout passes. Returns Lines, Final and Stopped.
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$TaskName,
        [Parameter(Mandatory)][string]$StatePath,
        [int]$TimeoutSeconds = 240,
        [int]$PollIntervalSeconds = 3,
        [string]$Label = 'repair as SYSTEM',
        [scriptblock]$OnProgress
    )
    $final = $null
    $lines = @()
    $stopped = $null
    $attempts = [int][math]::Ceiling($TimeoutSeconds / $PollIntervalSeconds)
    for ($i = 1; $i -le $attempts -and -not $final -and -not $stopped; $i++) {
        Start-Sleep -Seconds $PollIntervalSeconds
        $lines = @(Get-ICTSystemScriptState -Path $StatePath)
        $final = $lines | Where-Object { $_.Stage -eq 'end' } | Select-Object -Last 1
        if (-not $final) {
            $task = Get-ICTSystemTaskState -TaskName $TaskName
            if ($null -eq $task -or ($task.State -ne 'Running' -and $task.State -ne 'Queued')) {
                $lines = @(Get-ICTSystemScriptState -Path $StatePath)   # it may have finished just now
                $final = $lines | Where-Object { $_.Stage -eq 'end' } | Select-Object -Last 1
                if (-not $final) { $stopped = $(if ($task) { $task } else { [pscustomobject]@{ State = 'missing'; LastTaskResult = $null } }) }
            }
        }
        if ($OnProgress) {
            $last = $lines | Select-Object -Last 1
            & $OnProgress ('{0}: {1} ({2} s)' -f $Label, $(if ($last) { $last.Stage } else { 'starting' }), ($i * $PollIntervalSeconds))
        }
    }
    return [pscustomobject]@{ Lines = $lines; Final = $final; Stopped = $stopped }
}
